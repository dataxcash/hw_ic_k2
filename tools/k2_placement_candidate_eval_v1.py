#!/usr/bin/env python3
"""k2_placement_candidate_eval_v1.py --- #K2-337 window C asset: scheme-layer scoring of placement candidates.

Scores each candidate generated by tools/k2_placement_generate_v1.py against
  * the extracted placement norms N1..N7 (L2/PLACEMENT_NORMS_v1.json)   -> machine version, named threshold
  * the C16 component-level keepout (pad-bbox pairwise, all items AT CANDIDATE POSITIONS)
  * the SCHEME gate criteria that are computable from PLACEMENT GEOMETRY ALONE (P3 exact; P1/P4 proxy readings)
Criteria whose threshold or source is NOT in register are reported PENDING with the reason - no invented
thresholds (same rule as tools/k2_placement_gate_v1.py).

Reads the as-built board read-only for pad geometry + net membership.  Writes L2/PLACEMENT_CANDIDATE_SCORES_v1.json.

Usage: k2_placement_candidate_eval_v1.py --board hw/k2_v4_8L.l10.kicad_pcb --candidates <json> [--out <json>]
"""
import argparse, collections, json, math, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "pm_gate", "artifacts", "k2_v4")
NORMS_PATH = os.path.join(ART, "L2", "PLACEMENT_NORMS_v1.json")
SOL_PATH = os.path.join(ART, "L2", "PLACEMENT_SOLUTION_v1.json")
CAND_PATH = os.path.join(ART, "L2", "PLACEMENT_CANDIDATES_v1.json")
OUT_PATH = os.path.join(ART, "L2", "PLACEMENT_CANDIDATE_SCORES_v1.json")

MARGIN = 0.20            # C16 keepout margin (same as tools/k2_keepout_component_v1.py)
HS_NET_PREFIXES = ("PCIE", "REFCLK")
CORNER_MAX = 3.0         # N3 / P3 (#K2-322 sec.3.1)
EDGE_MIN = 0.3           # N3 (#K2-322 sec.3.1)
CENTRE_TOL = 0.15        # N1 (L2/PLACEMENT_NORMS_v1 N1.param.centre_tol_frac)
QUAD_MAX_RATIO = 1.5     # N5 (L2/PLACEMENT_NORMS_v1 N5.param.quadrant_max_ratio)
LEDGE_PIN_HEADERS = ["J12", "J6", "J13", "J11", "J9"]   # left pin-header column (low-speed interface)
CHIP = "U6"


def mm(v):
    return round(v, 3)


def boxes(fp, dx=0.0, dy=0.0):
    out = []
    for p in fp.Pads():
        b = p.GetBoundingBox()
        out.append((mm(pcbnew.ToMM(b.GetLeft())) + dx, mm(pcbnew.ToMM(b.GetTop())) + dy,
                    mm(pcbnew.ToMM(b.GetRight())) + dx, mm(pcbnew.ToMM(b.GetBottom())) + dy))
    return out


def overlap(a, b, m=MARGIN):
    return not (a[2] + m <= b[0] or b[2] + m <= a[0] or a[3] + m <= b[1] or b[3] + m <= a[1])


def bbox_union(bs):
    return (min(b[0] for b in bs), min(b[1] for b in bs), max(b[2] for b in bs), max(b[3] for b in bs))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--board", required=True)
    ap.add_argument("--candidates", default=CAND_PATH)
    ap.add_argument("--out", default=OUT_PATH)
    a = ap.parse_args()
    try:
        import pcbnew
    except Exception as e:
        print(json.dumps({"error": "pcbnew missing: %r" % e})); return 3
    globals()["pcbnew"] = pcbnew

    b = pcbnew.LoadBoard(a.board)
    e = b.GetBoardEdgesBoundingBox()
    X0, X1, Y0, Y1 = mm(pcbnew.ToMM(e.GetLeft())), mm(pcbnew.ToMM(e.GetRight())), \
        mm(pcbnew.ToMM(e.GetTop())), mm(pcbnew.ToMM(e.GetBottom()))
    cx, cy = (X0 + X1) / 2.0, (Y0 + Y1) / 2.0
    W, H = X1 - X0, Y1 - Y0
    corners = {"TL": (X0, Y0), "TR": (X1, Y0), "BL": (X0, Y1), "BR": (X1, Y1)}

    nets = {c: ni.GetNetname() for c, ni in b.GetNetInfo().NetsByNetcode().items()}
    fps = {fp.GetReference(): fp for fp in b.GetFootprints()}
    l10_at, base_boxes, hs_refs = {}, {}, set()
    for r, fp in fps.items():
        l10_at[r] = (mm(pcbnew.ToMM(fp.GetPosition().x)), mm(pcbnew.ToMM(fp.GetPosition().y)))
        base_boxes[r] = boxes(fp)
        for p in fp.Pads():
            nm = nets.get(p.GetNetCode(), "")
            if nm.startswith(HS_NET_PREFIXES):
                hs_refs.add(r)
                break
    hole_refs = sorted(r for r in fps if r.startswith("H") and r[1:].isdigit())
    for r in hole_refs:
        hs_refs.discard(r)

    norms = {n["id"]: n for n in json.load(open(NORMS_PATH, encoding="utf-8"))["norms"]}
    cands = json.load(open(a.candidates, encoding="utf-8"))
    sol = json.load(open(SOL_PATH, encoding="utf-8"))

    reports = []
    for cand in cands["candidates"]:
        refs = cand["refs"]
        hole_at = cand["framework"]["holes"]
        at = {r: (refs[r][0], refs[r][1]) for r in refs}
        for h, p in hole_at.items():
            at[h] = (p[0], p[1])
        item_boxes = {}
        for r, ab in base_boxes.items():
            if r not in at:
                continue
            dx = at[r][0] - l10_at[r][0]
            dy = at[r][1] - l10_at[r][1]
            item_boxes[r] = [(bb[0] + dx, bb[1] + dy, bb[2] + dx, bb[3] + dy) for bb in ab]
        moved = sorted({r for r in item_boxes if r not in l10_at or
                        abs(at[r][0] - l10_at[r][0]) > 1e-6 or abs(at[r][1] - l10_at[r][1]) > 1e-6})

        # ---------------- C16 component-level keepout (candidate positions) ----------------
        coll = []
        for i, m in enumerate(moved):
            for o in item_boxes:
                if o == m:
                    continue
                for mb in item_boxes[m]:
                    for ob in item_boxes[o]:
                        if overlap(mb, ob):
                            coll.append({"a": m, "b": o, "a_box": mb, "b_box": ob,
                                         "gap_hint_mm": round(max(ob[0] - mb[2], mb[0] - ob[2],
                                                                  ob[1] - mb[3], mb[1] - ob[3]), 3)})
        c16_pairs = sorted({(c["a"], c["b"]) for c in coll})
        oob = []
        for m in moved:
            for bb in item_boxes[m]:
                if bb[0] < X0 + 0.5 or bb[2] > X1 - 0.5 or bb[1] < Y0 + 0.5 or bb[3] > Y1 - 0.5:
                    oob.append({"ref": m, "box": bb})
        # crux: for every MOVED item, the named partners it collides with (the actionable repair surface)
        crux = collections.OrderedDict()
        for pr in c16_pairs:
            for moved_r, other in ((pr[0], pr[1]), (pr[1], pr[0])):
                if moved_r in moved:
                    crux.setdefault(moved_r, [])
                    if other not in crux[moved_r]:
                        crux[moved_r].append(other)
        C16 = {"gate": "C16 component-level keepout (pad-bbox pairwise, margin %.2fmm, all items at candidate positions)" % MARGIN,
               "n_items": len(item_boxes), "moved": moved,
               "collision_pairs": [{"a": p[0], "b": p[1]} for p in c16_pairs],
               "n_collision_pairs": len(c16_pairs), "n_collision_boxes": len(coll),
               "out_of_board": oob[:10], "n_out_of_board": len(oob),
               "crux": crux,
               "verdict": "PASS" if (not coll and not oob) else "FAIL",
               "note": "footprint-vs-footprint only; candidate tracks are NOT checked (no re-route; C17)"}

        # ---------------- N1 chip centring ----------------
        chip = cand["framework"]["chip"]["ref"]
        dxc, dyc = at[chip][0] - cx, at[chip][1] - cy
        N1 = {"norms": ["N1"], "threshold": "|dx|<=%.2f*W=%.2fmm and |dy|<=%.2f*H=%.2fmm"
                        % (CENTRE_TOL, CENTRE_TOL * W, CENTRE_TOL, CENTRE_TOL * H),
              "source": norms["N1"]["source"], "chip": chip, "at": list(at[chip]),
              "centre": [round(cx, 3), round(cy, 3)], "dx_mm": round(dxc, 2), "dy_mm": round(dyc, 2),
              "verdict": "PASS" if (abs(dxc) <= CENTRE_TOL * W and abs(dyc) <= CENTRE_TOL * H) else "FAIL"}

        # ---------------- N2 connector edge / fan-out alignment ----------------
        # READ (l10): HS connectors = J2 (east of the chip) + J3,J4 (west).  This board is a 2-port converter,
        # so L1 fixes high-speed connectors on BOTH sides of the chip => the exemplar's single-edge clause is a
        # STRUCTURAL DIFFERENCE, not an achievable placement target => PENDING (no invented verdict either way).
        j2 = cand["framework"]["connectors"]["J2"]["at"]
        hs_conn = sorted(r for r in hs_refs if r != chip and r in at)
        N2 = {"norms": ["N2"], "source": norms["N2"]["source"], "verdict": "PENDING",
              "hs_connectors": {r: ("east_of_chip" if at[r][0] > at[chip][0] else "west_of_chip") for r in hs_conn},
              "chip_to_J2_vec_mm": [round(j2[0] - at[chip][0], 2), round(j2[1] - at[chip][1], 2)],
              "note": ("exemplar N2 = HS connectors on ONE edge; K2 L1 fixes a 2-sided HS interface "
                       "(J2 east, J3/J4 west) - structural difference (see #K2-336 sec.1 diff list) => PENDING")}

        # ---------------- N3 / P3 mounting holes four-corner ----------------
        holes = []
        for h in sorted(hole_at):
            p = at[h]
            nc = min(corners.items(), key=lambda kv: math.hypot(p[0] - kv[1][0], p[1] - kv[1][1]))
            dist = math.hypot(p[0] - nc[1][0], p[1] - nc[1][1])
            edge = min(p[0] - X0, X1 - p[0], p[1] - Y0, Y1 - p[1])
            holes.append({"hole": h, "at": list(p), "nearest_corner": nc[0],
                          "corner_dist_mm": round(dist, 2), "edge_margin_mm": round(edge, 2),
                          "pass": dist <= CORNER_MAX + 1e-9 and edge >= EDGE_MIN - 1e-9})
        N3 = {"norms": ["N3"], "thresholds": {"corner_max_mm": CORNER_MAX, "edge_min_mm": EDGE_MIN},
              "source": norms["N3"]["source"], "holes": holes,
              "worst_corner_mm": round(max(h["corner_dist_mm"] for h in holes), 2),
              "verdict": "PASS" if all(h["pass"] for h in holes) else "FAIL"}
        P3 = {"layer": "SCHEME", "thresholds": {"corner_max_mm": CORNER_MAX, "edge_min_mm": EDGE_MIN},
              "source": "#K2-322 sec.3.1", "holes": holes, "verdict": N3["verdict"]}

        # ---------------- N5 density balance (quadrant pad-area ratio) ----------------
        area = collections.defaultdict(float)
        cnt = collections.Counter()
        for r, bs in item_boxes.items():
            if r in hole_refs or r in hs_refs:
                continue
            cxp, cyp = at[r]
            q = ("Q1" if cxp < cx and cyp < cy else "Q2" if cxp >= cx and cyp < cy else
                 "Q3" if cxp < cx and cyp >= cy else "Q4")
            for bb in bs:
                area[q] += max(0.0, bb[2] - bb[0]) * max(0.0, bb[3] - bb[1])
            cnt[q] += 1
        mean = sum(area.values()) / 4.0
        ratio = (max(area.values()) / mean) if mean > 0 else None
        N5 = {"norms": ["N5"], "metric": "quadrant pad-bbox area share (proxy for courtyard area; F.CrtYd empty on this board)",
              "threshold": "max quadrant area / mean <= %.2f" % QUAD_MAX_RATIO, "source": norms["N5"]["source"],
              "quadrant_area_mm2": {q: round(area[q], 1) for q in ("Q1", "Q2", "Q3", "Q4")},
              "quadrant_parts": dict(cnt), "max_ratio": round(ratio, 2) if ratio else None,
              "verdict": "PASS" if (ratio is not None and ratio <= QUAD_MAX_RATIO) else "FAIL"}
        R3 = {"layer": "SCHEME", "checklist": "R3 density balance", "metric": N5["metric"],
              "reading": N5["quadrant_area_mm2"], "max_ratio": N5["max_ratio"],
              "verdict": N5["verdict"], "source": norms["N5"]["source"]}

        # ---------------- N6 high/low-speed zone separation (reading) ----------------
        hs_boxes = [bb for r in hs_refs if r in item_boxes for bb in item_boxes[r]]
        ls_boxes = [bb for r in item_boxes if r not in hs_refs and r not in hole_refs for bb in item_boxes[r]]
        hsb, lsb = bbox_union(hs_boxes), bbox_union(ls_boxes)
        N6 = {"norms": ["N6"], "threshold_mm": 2.0, "source": norms["N6"]["source"],
              "hs_group_bbox": [round(v, 2) for v in hsb], "low_speed_group_bbox": [round(v, 2) for v in lsb],
              "verdict": "PENDING",
              "note": "bounding-box overlap is structural on this board (chip-adjacent passives sit inside the HS box); a machine zone-gap reading needs a per-part functional-class map (not in register) - no invented threshold"}

        # ---------------- N4 functional partitioning (reading) ----------------
        non_hs = [r for r in item_boxes if r not in hs_refs and r not in hole_refs]
        left = [r for r in non_hs if at[r][0] < cx]
        N4 = {"norms": ["N4"], "source": norms["N4"]["source"], "n_non_hs_parts": len(non_hs),
              "left_share": round(len(left) / len(non_hs), 2) if non_hs else None,
              "verdict": "PENDING",
              "note": "needs a per-part functional-class map (power / interface / control / storage) which is not in register"}

        # ---------------- N7 flow (fan-out direction consistency) ----------------
        # Machine check: every HS connector must sit on the side of the chip it belongs to (west connectors west,
        # east connector east) => no connector is stranded behind the chip (no forced reverse crossing).
        west = sorted(r for r in hs_conn if at[r][0] < at[chip][0])
        east = sorted(r for r in hs_conn if at[r][0] > at[chip][0])
        N7 = {"norms": ["N7"], "source": norms["N7"]["source"], "chip": chip, "chip_x": at[chip][0],
              "west_connectors": west, "east_connectors": east,
              "verdict": "PASS" if (east and west and (at[west[-1]][0] < at[chip][0] < at[east[0]][0])) else "FAIL",
              "note": ("direction consistency only; the exemplar's intra-PAIR equal-length clause is a ROUTING "
                       "property -> PENDING at the placement layer")}

        # ---------------- P1 / P2 / P4 / P5 / P7 ----------------
        dl = round(j2[0] - at[chip][0], 2)
        P1 = {"layer": "SCHEME", "verdict": "PENDING",
              "source": "proxy threshold 1.6x is a PLACEHOLDER (vendor EVM guide not parsed yet); the real reading needs a routed board",
              "proxy": {"main_path_straight_delta_vs_baseline_mm": round(dl - (sol["refs"]["J2"]["at"][0] - sol["refs"]["U6"]["at"][0]), 2),
                        "chip_to_connector_straight_mm": dl},
              "note": "C17 (no re-route) blocks the routed reading"}
        secs = [x for x in (30, 45, 60, 75, 90, 105, 120, 134)]
        sec_cross = []
        for xs in secs:
            n = 0
            for r, bs in item_boxes.items():
                if r in hole_refs:
                    continue
                xs_ = sorted({bb[0] for bb in bs} | {bb[2] for bb in bs})
                if min(xs_) < xs < max(xs_):
                    n += 1
            sec_cross.append({"x_mm": xs, "parts_spanning": n})
        P4 = {"layer": "SCHEME", "verdict": "PENDING", "source": "R537 cross-section method (capacity>=demand; per-section supply not auto-derived here)",
              "sections": sec_cross, "note": "section supply (layer x row budget) not in register"}
        P2 = {"layer": "SCHEME", "verdict": "PENDING", "source": "PCIe Gen5 channel length budget file NOT in register"}
        P5 = {"layer": "CONSTRUCTION", "verdict": "PENDING", "source": "no in-register thermal file"}
        P7 = {"layer": "CONSTRUCTION", "verdict": "PENDING", "source": "SPEC pd.decoupling is a string; no machine-readable cap->load map"}

        crit = {"N1": N1, "N2": N2, "N3": N3, "N4": N4, "N5": N5, "N6": N6, "N7": N7,
                "C16_keepout": C16, "P1": P1, "P2": P2, "P3": P3, "P4": P4, "P5": P5, "P7": P7}
        fails = [k for k, v in crit.items() if v["verdict"] == "FAIL"]
        pends = [k for k, v in crit.items() if v["verdict"] == "PENDING"]
        reports.append({
            "id": cand["id"], "label": cand["label"], "norms_instantiated": cand["norms_instantiated"],
            "criteria": crit, "FAIL": fails, "PENDING": pends,
            "verdict": "FAIL" if fails else ("PENDING" if pends else "PASS"),
            "freezable": False,
            "freeze_blocker": ("SCHEME gate incomplete: P1/P2/P4/P5/P7 PENDING (thresholds/sources not in register) "
                               "=> no candidate can be frozen (fail-closed)") if pends else "none",
        })

    # ---- derived cross-candidate findings (mechanical: read off the C16 crux tables, no hand-waving) ----
    cross = []
    for c in reports:
        cx16 = c["criteria"]["C16_keepout"]
        for moved_r, partners in cx16.get("crux", {}).items():
            for o in partners:
                cross.append({"candidate": c["id"], "moved": moved_r, "blocked_by": o,
                              "blocker_class": ("LEFT_PIN_HEADER_COLUMN" if o in LEDGE_PIN_HEADERS else
                                                "CHIP_PERIPHERY_PASSIVE" if (moved_r == CHIP and o.startswith(("C", "R"))) else
                                                "OTHER")})
    seen, uniq = set(), []
    for f in cross:
        k = (f["candidate"], f["moved"], f["blocked_by"])
        if k not in seen:
            seen.add(k); uniq.append(f)

    rep = {"artifact": "k2_placement_candidate_scores_v1", "ts": "2026-09-28",
           "authority": "#K2-337 window C: seven-gate + R1-R6 scheme scoring of rule-driven placement candidates",
           "schema": "k2.placement_candidate_scores.v1",
           "evaluator": "tools/k2_placement_candidate_eval_v1.py",
           "board": a.board, "board_frame": {"x": [X0, X1], "y": [Y0, Y1], "centre": [round(cx, 3), round(cy, 3)]},
           "candidates": reports,
           "cross_candidate_findings": cross,
           "scheme_gate_status": "INCOMPLETE (P1/P2/P4/P5/P7 PENDING) => fail-closed: no candidate freezable"}
    with open(a.out, "w", encoding="utf-8") as f:
        json.dump(rep, f, ensure_ascii=False, indent=1)
    print(json.dumps({"wrote": a.out,
                      "per_candidate": {c["id"]: {"verdict": c["verdict"], "FAIL": c["FAIL"], "PENDING": c["PENDING"]} for c in reports}},
                     ensure_ascii=False, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
